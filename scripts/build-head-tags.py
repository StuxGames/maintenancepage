#!/usr/bin/env python3
"""Regenerate the shared <head> tags of every page on this static site.

Run from anywhere: python scripts/build-head-tags.py   (--check only reports stale pages)
scripts/build-sitemap.py runs it too, after it rebuilds sitemap/index.html.

Between the BEGIN/END markers in each page's <head> it writes:
- the icon tags (favicon.ico, the 512px PNG, apple-touch-icon.png, site.webmanifest), the same
  on every page;
- a Discord component embed (<script id="discord:component-embed">), a custom link preview built
  from the page's own title and description. Discord shows the normal preview instead when the
  block is missing or left out (a comment is written instead when it would be over Discord's
  3,000-byte limit). Error pages (404.html) get the icon tags only.
Spec: https://docs.discord.com/developers/link-previews/component-embeds

Copyright (c) Stux.Group. All Rights Reserved.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://" + (ROOT / "CNAME").read_text(encoding="utf-8").strip()

SITE_NAME = "Stux.Games Maintenance"
BRAND_COLOUR = "#FFBA1A"
ICON_URL = "https://global.media.stux.games/icon.png"
HOME_DESC = "This game or site is down for maintenance and respawning shortly."
HOME_EXTRA = "Nothing's lost, it'll be back before the next round starts."
HOME_FOOTER = ""
HOME_BUTTONS = [
    ("Live status", "https://status.stux.games"),
    ("Stux.Games", "https://stux.games"),
    ("Every game", "https://games.stux.games"),
]
EMBED_MAX_BYTES = 3000

BEGIN = "<!-- BEGIN head tags: generated by scripts/build-head-tags.py, edit there -->"
END = "<!-- END head tags -->"

FAVICON_TAGS = [
    '<link rel="icon" href="/favicon.ico" sizes="48x48">',
    '<link rel="icon" type="image/png" sizes="512x512" href="/assets/icon-512.png">',
    '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
    '<link rel="manifest" href="/site.webmanifest">',
]

# (source file, public path); 404.html is an error page and gets no embed.
PAGES = [
    ("index.html", "/"),
    ("changelog.html", "/changelog"),
    ("legal.html", "/legal"),
    ("legal/privacy.html", "/legal/privacy"),
    ("legal/terms.html", "/legal/terms"),
    ("legal/cookies.html", "/legal/cookies"),
    ("legal/imprint.html", "/legal/imprint"),
    ("legal/disclaimer.html", "/legal/disclaimer"),
    ("legal/opt-out.html", "/legal/opt-out"),
    ("sitemap/index.html", "/sitemap/"),
]
PAGES = [(src, path) for src, path in PAGES if (ROOT / src).is_file()]  # not every copy has a sitemap page
ERROR_PAGES = ["404.html"]

LEGAL_PAGES = [
    ("Privacy Policy", "/legal/privacy"), ("Terms and Ethics", "/legal/terms"),
    ("Cookies Policy", "/legal/cookies"), ("Imprint", "/legal/imprint"),
    ("Disclaimer", "/legal/disclaimer"), ("Opt-Out Preferences", "/legal/opt-out"),
]


# ── Discord component embed ────────────────────────────────────────────────

def discord_md(s: str) -> str:
    """Escapes Discord markdown so data (titles, descriptions) shows as plain text."""
    # Inline formatting, link brackets and backslashes anywhere; headings, quotes and lists only at a line start.
    s = re.sub(r"([\\*_~`|\[\]])", r"\\\1", s)
    return re.sub(r"(?m)^([#>-])", r"\\\1", s)


def discord_text(markdown: str) -> dict:
    return {"type": 10, "content": markdown}


def discord_buttons(links: list) -> dict:
    """A row of link buttons from (label, absolute URL) pairs. Buttons may only use these keys."""
    return {"type": 1, "components": [{"type": 2, "style": 5, "label": label[:80], "url": url} for label, url in links]}


def discord_section(markdown: str) -> dict:
    """Text with the Stux.Group icon beside it."""
    return {"type": 9, "components": [discord_text(markdown)], "accessory": {"type": 11, "media": {"url": ICON_URL}}}


def discord_payload(components: list, accent: str = BRAND_COLOUR):
    """The JSON payload, or None when it's over Discord's 3,000-byte limit."""
    payload = {"component": {"type": 17, "accent_color": int(accent.lstrip("#"), 16), "components": components}}
    data = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    data = data.replace("</", "<\\/")  # can't close the <script> early; JSON reads <\/ back as </
    return None if len(data.encode("utf-8")) > EMBED_MAX_BYTES else data


def discord_embed(components: list, accent: str = BRAND_COLOUR) -> str:
    """The <script> tag, or a comment when it would be over the limit (Discord then shows its normal preview)."""
    data = discord_payload(components, accent)
    if data is None:
        return f"<!-- discord:component-embed left out: over {EMBED_MAX_BYTES} bytes -->"
    return '<script id="discord:component-embed" type="application/json">' + data + "</script>"


def discord_abs(path: str) -> str:
    return BASE_URL + path


def discord_site_label() -> str:
    """The small site name above a page's title (Discord subtext), like a normal preview's."""
    return f"-# [{discord_md(SITE_NAME)}]({discord_abs('/')})\n"


def discord_home_embed(desc: str) -> str:
    """The maintenance page itself: what's going on and where to look."""
    components = [
        discord_section(f"# [Under maintenance]({discord_abs('/')})\n**{discord_md(desc)}**\n{discord_md(HOME_EXTRA)}"),
        {"type": 14},
    ]
    if HOME_FOOTER:
        components.append(discord_text("-# " + discord_md(HOME_FOOTER)))
    components.append(discord_buttons(HOME_BUTTONS))
    return discord_embed(components)


def discord_legal_embed(title: str, desc: str, url: str) -> str:
    """The legal hub: its six pages as links."""
    links = " · ".join(f"[{discord_md(name)}]({discord_abs(path)})" for name, path in LEGAL_PAGES)
    return discord_embed([
        discord_section(discord_site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        discord_text(links),
        discord_buttons([("Open", url), ("Home", discord_abs("/"))]),
    ])


def discord_page_embed(title: str, desc: str, url: str) -> str:
    """Any other page: its name and description, with a way back home."""
    return discord_embed([
        discord_section(discord_site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        discord_buttons([("Open", url), ("Home", discord_abs("/"))]),
    ])


# ── Pages ──────────────────────────────────────────────────────────────────

def page_meta(text: str):
    """(title without the site suffix, description) from a page's <head>."""
    title = html.unescape(re.search(r"<title>(.*?)</title>", text, re.S).group(1)).strip()
    desc = html.unescape(re.search(r'<meta name="description" content="([^"]*)"', text).group(1)).strip()
    return re.sub(r"\s+(\||—|-|·)\s.*$", "", title), desc


def embed_for(src: str, path: str, text: str) -> str:
    title, desc = page_meta(text)
    url = discord_abs(path)
    if src == "index.html":
        return discord_home_embed(HOME_DESC)
    if src == "legal.html":
        return discord_legal_embed("Boring Legal Stuff", desc, url)
    return discord_page_embed(title, desc, url)


def block(embed=None, indent: str = "    ") -> str:
    lines = [BEGIN] + FAVICON_TAGS
    if embed:
        lines.append(embed)
    return "\n".join(indent + line for line in lines + [END])


def render(text: str, embed=None) -> str:
    """The page with its generated block replaced, or added after the viewport meta the first time."""
    new = block(embed)
    pattern = re.compile(r"^[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END), re.S | re.M)
    if pattern.search(text):
        return pattern.sub(lambda _m: new, text, count=1)
    # First run: the generated block replaces the old icon links.
    text = re.sub(r'^[ \t]*<link rel="icon"[^>]*>\n', "", text, flags=re.M)
    anchor = re.search(r'^[ \t]*<meta name="viewport"[^>]*>\n', text, re.M)
    return text[:anchor.end()] + new + "\n" + text[anchor.end():]


def build():
    """{path: new text} for every page."""
    out = {}
    for src, path in PAGES:
        text = (ROOT / src).read_text(encoding="utf-8")
        out[src] = render(text, embed_for(src, path, text))
    for src in ERROR_PAGES:
        out[src] = render((ROOT / src).read_text(encoding="utf-8"))
    return out


def main(argv) -> int:
    check = "--check" in argv
    stale = []
    for src, text in build().items():
        file = ROOT / src
        if file.read_text(encoding="utf-8") != text:
            stale.append(src)
            if not check:
                file.write_text(text, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date (run python scripts/build-head-tags.py): " + ", ".join(stale))
            return 1
        print("All page head tags are up to date.")
        return 0
    print(f"Updated {len(stale)} page(s)" + (": " + ", ".join(stale) if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
